#pragma once

#include <cstddef>
#include <cstdint>
#include <string>
#include <string_view>

namespace bikeos {

struct Glyph {
    std::uint32_t codepoint{};
    std::uint32_t bitmap_offset{};  // into Font::bitmap, 4-bit alpha, two pixels per byte, rows padded to bytes
    std::uint8_t width{};
    std::uint8_t height{};
    std::int8_t x_offset{};
    std::int8_t y_offset{};  // top of the bitmap relative to the baseline (negative is above)
    std::uint8_t advance{};
};

struct Font {
    const Glyph* glyphs{};
    std::uint16_t glyph_count{};
    const std::uint8_t* bitmap{};
    std::uint8_t ascent{};
    std::uint8_t descent{};

    const Glyph* find(std::uint32_t codepoint) const;
};

// Generated by tools/generate_fonts.py from DejaVu Sans (Bitstream Vera license).
extern const Font font_distance;  // Bold 30 px; digits, '.', ',', 'k', 'm', ' '
extern const Font font_heading;   // Bold 22 px; ASCII and '…'
extern const Font font_title;     // Bold 15 px; Latin-1
extern const Font font_small;     // Regular 12 px; Latin-1
extern const Font font_label;     // Bold 11 px; Latin-1

// Decodes one UTF-8 code point starting at `index`, advancing it. Invalid
// bytes decode as '?' so a corrupt street name never stalls rendering.
std::uint32_t next_codepoint(std::string_view utf8, std::size_t& index);
int text_width(const Font& font, std::string_view utf8);
// Shortens `utf8` with a trailing ellipsis so it fits in `max_width` pixels.
std::string fit_text(const Font& font, std::string_view utf8, int max_width);

}  // namespace bikeos
