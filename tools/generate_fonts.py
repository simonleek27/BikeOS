#!/usr/bin/env python3
"""Rasterise DejaVu Sans into 4-bit alpha bitmap fonts for the color TFT.

Writes core/src/font_data.cpp. DejaVu Sans ships with matplotlib, so
`pip install pillow matplotlib` is all that is needed. DejaVu fonts are
distributed under the Bitstream Vera / DejaVu license, which permits
embedding the glyphs in firmware.
"""

from __future__ import annotations

import argparse
import pathlib

import matplotlib
from PIL import ImageFont

LATIN1 = [*range(0x20, 0x7F), *range(0xA0, 0x100), 0x2026, 0x2013]
DISTANCE = [ord(c) for c in " 0123456789.,km"]

FONTS = [
    # name, file, pixel size, code points
    ("font_distance", "DejaVuSans-Bold.ttf", 30, DISTANCE),
    ("font_heading", "DejaVuSans-Bold.ttf", 22, [*range(0x20, 0x7F), 0x2026]),
    ("font_title", "DejaVuSans-Bold.ttf", 15, LATIN1),
    ("font_small", "DejaVuSans.ttf", 12, LATIN1),
    ("font_label", "DejaVuSans-Bold.ttf", 11, LATIN1),
]


def font_path(name: str) -> pathlib.Path:
    return pathlib.Path(matplotlib.get_data_path()) / "fonts" / "ttf" / name


def rasterise(name: str, file: str, size: int, codepoints: list[int]) -> str:
    font = ImageFont.truetype(str(font_path(file)), size)
    ascent, descent = font.getmetrics()
    bitmap: list[int] = []
    glyphs = []
    for codepoint in sorted(set(codepoints)):
        char = chr(codepoint)
        advance = round(font.getlength(char))
        mask, (left, top) = font.getmask2(char, mode="L", anchor="ls")
        width, height = mask.size
        offset = len(bitmap)
        if width and height:
            stride = (width + 1) // 2
            for y in range(height):
                row = [0] * stride
                for x in range(width):
                    level = (mask.getpixel((x, y)) + 8) // 17
                    level = max(0, min(15, level))
                    row[x // 2] |= level << (4 if x % 2 == 0 else 0)
                bitmap.extend(row)
        glyphs.append((codepoint, offset, width, height, left, top, advance))

    lines = [f"// {name}: {file} {size}px, {len(glyphs)} glyphs, {len(bitmap)} bytes"]
    lines.append(f"constexpr std::uint8_t {name}_bitmap[] = {{")
    for start in range(0, len(bitmap), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in bitmap[start:start + 24]) + ",")
    if not bitmap:
        lines.append("    0x00,")
    lines.append("};")
    lines.append(f"constexpr Glyph {name}_glyphs[] = {{")
    for codepoint, offset, width, height, left, top, advance in glyphs:
        lines.append(
            f"    {{0x{codepoint:04x}, {offset}, {width}, {height}, {left}, {top}, {advance}}},"
        )
    lines.append("};")
    return "\n".join(lines), (name, len(glyphs), ascent, descent)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=pathlib.Path,
                        default=pathlib.Path(__file__).resolve().parents[1] / "core/src/font_data.cpp")
    args = parser.parse_args()
    sections = []
    definitions = []
    for name, file, size, codepoints in FONTS:
        source, (font_name, count, ascent, descent) = rasterise(name, file, size, codepoints)
        sections.append(source)
        definitions.append(
            f"const Font {font_name}{{{font_name}_glyphs, {count}, {font_name}_bitmap, {ascent}, {descent}}};"
        )
    output = "\n".join([
        "// Generated by tools/generate_fonts.py. Do not edit by hand.",
        "// Glyphs from DejaVu Sans (Bitstream Vera / DejaVu license).",
        '#include "bikeos/fonts.hpp"',
        "",
        "namespace bikeos {",
        "namespace {",
        "",
        "\n\n".join(sections),
        "",
        "}  // namespace",
        "",
        "\n".join(definitions),
        "",
        "}  // namespace bikeos",
        "",
    ])
    args.output.write_text(output)
    print(f"wrote {args.output} ({len(output) // 1024} KiB of source)")


if __name__ == "__main__":
    main()
